local function loopTween(obj, time, props, reverse)
	local tw = TweenService:Create(obj,
		TweenInfo.new(time, reverse and Enum.EasingStyle.Sine or Enum.EasingStyle.Linear,
			Enum.EasingDirection.InOut, -1, reverse and true or false, 0), props)
	tw:Play()
	table.insert(tweens, tw)
	return tw
end
local function tween(obj, t, props, style, dir)
	local tw = TweenService:Create(obj, TweenInfo.new(t, style or Enum.EasingStyle.Quad, dir or Enum.EasingDirection.Out), props)
	tw:Play()
	return tw
end
