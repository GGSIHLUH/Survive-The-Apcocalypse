	local broughtAt = setmetatable({}, { __mode = "k" })
	local function gatherBring()
		local root = getRoot()
		if not root then return {} end
		local w = {
			metal = on("Bring Metal"), gun = on("Bring Guns"), ammo = on("Bring Ammo"), item = on("Bring Item"),
			melee = on("Bring Melee"), food = on("Bring Food"), all = on("Bring All Item"),
		}
		local scan = on("Scanner Bring")
		local filter = scan and parseFilter(UI.getInput("Bring Filter")) or nil
		local range = val("Bring Range", 400)
		local dest = destCF()
		local out = {}
		for _, e in ipairs(Index.items) do
			local o = e.obj
			if o and o.Parent then
				local p = posOf(o)
				if p then
					local d = (p - root.Position).Magnitude
					local near = dest and (p - dest.Position).Magnitude < 6
					if d <= range and not near and not (broughtAt[o] and os.clock() - broughtAt[o] < 6) then
						local ok = w.all or w[e.cat]
						if not ok and scan then
							ok = (#filter == 0) or nameMatch(e.name, filter)
						end
						if ok then out[#out + 1] = { e = e, d = d } end
					end
				end
			end
		end
		table.sort(out, function(a, b) return a.d < b.d end)
		local function take(list, n)
			local r = {}
			for i = 1, math.min(n, #list) do r[i] = list[i] end
			return r
		end
		local function shuffle(list)
			for i = #list, 2, -1 do
				local j = math.random(1, i)
				list[i], list[j] = list[j], list[i]
			end
		end
		if on("Bring Nearest") and on("Bring Random") then
			out = take(out, 5)
			shuffle(out)
			out = take(out, 2)
		elseif on("Bring Nearest") then
			out = take(out, 3)
		elseif on("Bring Random") then
			shuffle(out)
			out = take(out, 3)
		else
			out = take(out, 30)
		end
		local res = {}
		for _, x in ipairs(out) do res[#res + 1] = x.e end
		return res
	end

	local function tweenAll(list, destFn)
		local maxT = 0
		local dest = destFn()
		if not dest then return end
		for _, e in ipairs(list) do
			local cf0 = getCF(e.obj)
			if cf0 then
				local cv = Instance.new("CFrameValue")
				cv.Value = cf0
				local dist = (dest.Position - cf0.Position).Magnitude
				local t = math.clamp(dist / 400, 0.3, 1.5)
				maxT = math.max(maxT, t)
				local c = cv.Changed:Connect(function(v)
					if e.obj.Parent then setCF(e.obj, v) end
				end)
				local tw = TweenService:Create(cv, TweenInfo.new(t, Enum.EasingStyle.Quad, Enum.EasingDirection.Out), { Value = dest })
				tw.Completed:Connect(function()
					c:Disconnect()
					cv:Destroy()
				end)
				tw:Play()
			end
		end
		task.wait(maxT)
	end

	local function moveItems(list, method, alive)
		boostOwnership()
		if method == "Tween" then
			tweenAll(list, destCF)
			return
		end
		if method == "Tp" then
			for _, e in ipairs(list) do
				local d = destCF()
				if d and e.obj.Parent then setCF(e.obj, d) end
				RunService.Heartbeat:Wait()
			end
			return
		end
		if method == "Instant (Lag)" then
			local d = destCF()
			if d then
				for _, e in ipairs(list) do
					if e.obj.Parent then setCF(e.obj, d) end
				end
			end
			return
		end
		if method == "0s (No Lag)" then
			local d = destCF()
			if d then
				for i, e in ipairs(list) do
					if e.obj.Parent then setCF(e.obj, d) end
					if i % 8 == 0 then RunService.Heartbeat:Wait() end
				end
			end
			return
		end
		-- Force / Fast / Smooth: gerak per frame
		local active = {}
		for _, e in ipairs(list) do active[#active + 1] = e end
		local t0 = os.clock()
		while #active > 0 and os.clock() - t0 < 10 and alive() do
			local dt = RunService.Heartbeat:Wait()
			local d = destCF()
			if not d then break end
			for i = #active, 1, -1 do
				local o = active[i].obj
				local cf = o.Parent and getCF(o)
				if not cf then
					table.remove(active, i)
				else
					local delta = d.Position - cf.Position
					local dist = delta.Magnitude
					if dist < 1.5 then
						setCF(o, d)
						table.remove(active, i)
					else
						local step
						if method == "Force" then step = val("Force Speed", 300) * dt
						elseif method == "Fast" then step = 900 * dt
						else step = dist * (1 - math.exp(-6 * dt)) end
						setCF(o, CFrame.new(cf.Position + delta.Unit * math.min(step, dist)) * (cf - cf.Position))
					end
				end
			end
		end
	end

