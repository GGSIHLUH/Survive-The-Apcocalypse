	-- ---------- Scan Game ----------
	local function scanGame()
		pcall(function() scanning = false scanIndex() end)
		scanning = false
		local out = {}
		local function add(s) out[#out + 1] = s end
		add(string.format("PlaceId %d | %s", game.PlaceId, tostring(game.Name)))

		add("== Remotes ==")
		local n = 0
		for _, d in ipairs(ReplicatedStorage:GetDescendants()) do
			if d:IsA("RemoteEvent") or d:IsA("RemoteFunction") then
				n += 1
				if n <= 120 then add(d.ClassName .. " " .. d:GetFullName()) end
			end
		end

		add(string.format("== Index: airdrop=%d campfire=%d grinder=%d metalNode=%d prompt=%d item=%d ==",
			#Index.airdrop, #Index.campfire, #Index.grinder, #Index.metalNodes, #Index.prompts, #Index.items))
		for _, key in ipairs({ "airdrop", "campfire", "grinder", "metalNodes" }) do
			add("-- " .. key)
			for i, o in ipairs(Index[key]) do
				if i > 12 then break end
				add(o:GetFullName())
			end
		end

		add("== NPC (humanoid non-player) ==")
		local seenN, c = {}, 0
		for m in pairs(npcSet) do
			if m.Parent and not seenN[m.Name] then
				seenN[m.Name] = true
				c += 1
				if c <= 40 then add(m.Name .. "  <- " .. (m.Parent and m.Parent.Name or "?")) end
			end
		end

		add("== Item (nama unik) ==")
		local seenI, ci = {}, 0
		for _, e in ipairs(Index.items) do
			if not seenI[e.name] then
				seenI[e.name] = true
				ci += 1
				if ci <= 50 then add(e.cat .. " : " .. e.name) end
			end
		end

		add("== Prompt (40 pertama) ==")
		for i, e in ipairs(Index.prompts) do
			if i > 40 then break end
			add(string.format("%s | %s / %s", e.path, tostring(e.p.ObjectText), tostring(e.p.ActionText)))
		end

		add("== Tool di Backpack ==")
		for _, t in ipairs(LocalPlayer.Backpack:GetChildren()) do
			add(t.Name .. " [" .. tostring(t.ToolTip) .. "] -> " .. toolKind(t))
		end

		local text = table.concat(out, "\n")
		local copied = false
		if setclipboard then copied = pcall(setclipboard, text) end
		print(text)
		hist(copied and "Scan Game disalin ke clipboard" or "Scan Game dicetak di console (F9)")
		toast(copied and "Hasil scan disalin" or "Hasil scan di console (F9)")
	end

