	local function containerOf(p)
		local par = p.Parent
		if par and par:IsA("Attachment") then par = par.Parent end
		if not par or par == workspace then return nil end
		if par:IsA("Model") or par:IsA("Tool") then return par end
		if par:IsA("BasePart") then
			local m = par.Parent
			if m and m ~= workspace and (m:IsA("Model") or m:IsA("Tool")) and #m:GetChildren() <= 15 then return m end
			return par
		end
		return nil
	end

	local function catOfName(n)
		n = n:lower()
		if nameMatch(n, PAT.ammo) then return "ammo" end
		if nameMatch(n, PAT.gun) then return "gun" end
		if nameMatch(n, PAT.melee) and not n:find("battery") then return "melee" end
		if nameMatch(n, PAT.metal) then return "metal" end
		if nameMatch(n, PAT.food) then return "food" end
		return "item"
	end

	local function addTop(list, d, n, pats)
		if nameMatch(n, pats) and not (d.Parent and nameMatch(d.Parent.Name, pats)) and not isCharacterPart(d) then
			list[#list + 1] = d
		end
	end

	local function scanIndex()
		if scanning then return end
		scanning = true
		local new = { airdrop = {}, campfire = {}, grinder = {}, metalNodes = {}, prompts = {}, items = {} }
		local seen = {}
		local n = 0
		for _, d in ipairs(workspace:GetDescendants()) do
			n += 1
			if n % 3000 == 0 then task.wait() end
			if d:IsA("ProximityPrompt") then
				local pos = promptPos(d)
				if pos then
					local path = pathLower(d)
					new.prompts[#new.prompts + 1] = { p = d, pos = pos, path = path }
					local obj = containerOf(d)
					if obj and not seen[obj] and not nameMatch(path, STRUCT_PAT) and not npcSet[obj] and not isCharacterPart(obj) then
						seen[obj] = true
						new.items[#new.items + 1] = { obj = obj, p = d, cat = catOfName(obj.Name), name = obj.Name }
					end
				end
			elseif d:IsA("Tool") then
				if d:FindFirstChild("Handle") and not seen[d] and not isCharacterPart(d) then
					seen[d] = true
					new.items[#new.items + 1] = { obj = d, p = nil, cat = catOfName(d.Name), name = d.Name }
				end
			elseif d:IsA("Model") or (d:IsA("BasePart") and not d:IsA("Terrain")) then
				local nm = d.Name:lower()
				if nameMatch(nm, PAT.airdrop) then
					addTop(new.airdrop, d, nm, PAT.airdrop)
				elseif nameMatch(nm, PAT.campfire) then
					addTop(new.campfire, d, nm, PAT.campfire)
				elseif nameMatch(nm, PAT.grinder) then
					addTop(new.grinder, d, nm, PAT.grinder)
				elseif nameMatch(nm, PAT.metal) and not npcSet[d] then
					local big = (d:IsA("BasePart") and d.Size.Magnitude > 3) or d:IsA("Model")
					if big and not d:FindFirstChildWhichIsA("ProximityPrompt", true) and not nm:find("fence") and not nm:find("wall") then
						addTop(new.metalNodes, d, nm, PAT.metal)
					end
				end
			end
		end
		Index = new
		indexAt = os.clock()
		scanning = false
	end

	local function waitIndex(alive)
		local t0 = os.clock()
		while indexAt == 0 and alive() and os.clock() - t0 < 20 do task.wait(0.2) end
