local function pwHash(user, pw)
	local s = "senar|" .. user:lower() .. "|" .. pw .. "|hub"
	local h1, h2 = 5381, 52711
	for i = 1, #s do
		local b = s:byte(i)
		h1 = (h1 * 33 + b) % 4294967296
		h2 = (h2 * 31 + b * (i % 7 + 1)) % 4294967296
	end
	return string.format("%08x%08x", math.floor(h1), math.floor(h2))
end

