local function makeSlider(parent, o)
	local holder = make("Frame", { Position = o.Position, Size = o.Size, BackgroundTransparency = 1 }, parent)
	local hit = make("TextButton", { Size = UDim2.fromScale(1, 1), BackgroundTransparency = 1, Text = "" }, holder)
	local track = make("Frame", {
		AnchorPoint = Vector2.new(0, 0.5), Position = UDim2.fromScale(0, 0.5), Size = UDim2.new(1, 0, 0, 6),
		BackgroundColor3 = Color3.fromRGB(24, 34, 60), BorderSizePixel = 0,
	}, hit)
	pill(track)
	local fill = make("Frame", { Size = UDim2.fromScale(0, 1), BackgroundColor3 = WHITE, BorderSizePixel = 0 }, track)
	pill(fill)
	make("UIGradient", { Color = ColorSequence.new(C.BLUE, C.GREEN) }, fill)
	local knob = make("Frame", {
		AnchorPoint = Vector2.new(0.5, 0.5), Position = UDim2.fromScale(0, 0.5), Size = UDim2.fromOffset(14, 14),
		BackgroundColor3 = WHITE, BorderSizePixel = 0, ZIndex = 2,
	}, track)
	pill(knob)
	local step = o.step or 1
	local value = o.value or o.min
	local function snap(v)
		v = math.clamp(v, o.min, o.max)
		v = o.min + math.floor((v - o.min) / step + 0.5) * step
		return math.clamp(v, o.min, o.max)
	end
	value = snap(value)
	local function render()
		local f = (value - o.min) / (o.max - o.min)
		fill.Size = UDim2.fromScale(f, 1)
		knob.Position = UDim2.fromScale(f, 0.5)
		if o.onVisual then o.onVisual(value) end
	end
	render()
	local obj = {}
	function obj.get() return value end
	function obj.set(v, silent)
		v = snap(v)
		if math.abs(v - value) < 1e-6 then return end
		value = v
		render()
		if not silent and o.onChange then o.onChange(value) end
	end
	local dragging = false
	local function fromInput(input)
		local w = track.AbsoluteSize.X
		if w <= 0 then return end
		obj.set(o.min + math.clamp((input.Position.X - track.AbsolutePosition.X) / w, 0, 1) * (o.max - o.min))
	end
	hit.InputBegan:Connect(function(input)
		if isPress(input) then
			dragging = true
			fromInput(input)
		end
	end)
	table.insert(conns, UserInputService.InputChanged:Connect(function(input)
		if dragging and (input.UserInputType == Enum.UserInputType.MouseMovement
			or input.UserInputType == Enum.UserInputType.Touch) then
			fromInput(input)
		end
	end))
	table.insert(conns, UserInputService.InputEnded:Connect(function(input)
		if dragging and isPress(input) then dragging = false end
	end))
	return obj
end

