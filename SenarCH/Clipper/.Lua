	end

	local function parseFilter(s)
		local out = {}
		for w in tostring(s or ""):gmatch("[^,]+") do
			w = w:gsub("^%s+", ""):gsub("%s+$", ""):lower()
			if w ~= "" then out[#out + 1] = w end
		end
		return out
	end

	local function anyBring()
		return on("Bring Metal") or on("Bring Guns") or on("Bring Ammo") or on("Bring Item") or on("Bring All Item")
