								local new, c1 = t:gsub("([Dd][Aa][Yy]%s*:?%s*)%d+", "%1" .. ns)
								if c1 == 0 then new, c1 = t:gsub("([Hh][Aa][Rr][Ii]%s*:?%s*)%d+", "%1" .. ns) end
								if c1 > 0 and new ~= t then
									dayOrig[d] = dayOrig[d] or t
									d.Text = new
								end
							end
						end
					end
				end
				task.wait(0.5)
